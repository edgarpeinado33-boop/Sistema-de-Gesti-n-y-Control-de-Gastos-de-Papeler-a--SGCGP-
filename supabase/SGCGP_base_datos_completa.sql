CREATE OR REPLACE FUNCTION public.validar_cambio_solicitud_SGCGP()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    IF (SELECT auth.uid()) IS NOT NULL AND NOT public.es_gestor_SGCGP() THEN
        IF OLD.usuario_id <> public.mi_id_usuario_SGCGP()
           OR OLD.estado <> 'pendiente' THEN
            RAISE EXCEPTION 'Solo puedes editar tus propias solicitudes pendientes.';
        END IF;
        IF NEW.usuario_id IS DISTINCT FROM OLD.usuario_id
           OR NEW.estado IS DISTINCT FROM OLD.estado
           OR NEW.revisado_por IS DISTINCT FROM OLD.revisado_por
           OR NEW.fecha_revision IS DISTINCT FROM OLD.fecha_revision
           OR NEW.observaciones IS DISTINCT FROM OLD.observaciones
           OR NEW.fecha_solicitud IS DISTINCT FROM OLD.fecha_solicitud THEN
            RAISE EXCEPTION 'No puedes modificar los campos de revisión de la solicitud.';
        END IF;
    END IF;
    NEW.updated_at := NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_solicitud_SGCGP ON public.solicitudes_gasto_SGCGP;
CREATE TRIGGER trg_validar_solicitud_SGCGP
BEFORE UPDATE ON public.solicitudes_gasto_SGCGP
FOR EACH ROW EXECUTE FUNCTION public.validar_cambio_solicitud_SGCGP();

