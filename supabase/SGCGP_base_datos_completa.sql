-- ============================================================
-- SGCGP: SISTEMA DE GESTION Y CONTROL DE GASTOS DE PAPELERIA
-- PostgreSQL / Supabase
-- Zona horaria de negocio: America/La_Paz
--
-- EJECUCION:
-- 1. Ejecutar en un proyecto Supabase de desarrollo.
-- 2. Revisar permisos y probar cada rol antes de usar datos reales.
-- 3. No exponer SUPABASE_SERVICE_ROLE_KEY en el navegador.
-- 4. Los modelos ML se entrenan en un servicio externo; aquí se guardan
--    sus metadatos, predicciones, alertas y recomendaciones.
--
-- Nota: el script es idempotente en buena parte, pero no es una migracion
-- universal para tablas preexistentes con columnas distintas.
-- ============================================================

BEGIN;

-- ============================================================
-- 1. FUNCIONES AUXILIARES DE IDENTIDAD Y ROL
-- ============================================================

CREATE OR REPLACE FUNCTION public.mi_id_usuario_SGCGP()
RETURNS INTEGER
LANGUAGE SQL STABLE SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT u.id_usuario
    FROM public.usuarios_SGCGP u
    WHERE u.auth_user_id = (SELECT auth.uid())
    LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.mi_rol_SGCGP()
RETURNS TEXT
LANGUAGE SQL STABLE SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT u.rol
    FROM public.usuarios_SGCGP u
    WHERE u.auth_user_id = (SELECT auth.uid())
      AND u.estado = TRUE
    LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.es_admin_SGCGP()
RETURNS BOOLEAN
LANGUAGE SQL STABLE SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT COALESCE(public.mi_rol_SGCGP() = 'administrador', FALSE);
$$;

CREATE OR REPLACE FUNCTION public.es_gestor_SGCGP()
RETURNS BOOLEAN
LANGUAGE SQL STABLE SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT COALESCE(
        public.mi_rol_SGCGP() IN ('administrador', 'encargado_gastos'),
        FALSE
    );
$$;

