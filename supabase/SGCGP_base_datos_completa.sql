-- 18. VISTA RESUMEN DE GASTOS POR CATEGORIA
-- ============================================================

CREATE OR REPLACE VIEW public.vista_resumen_gastos_SGCGP
WITH (security_invoker = true)
AS
SELECT
    c.id_categoria,
    c.nombre AS categoria,
    COUNT(g.id_gasto) FILTER (WHERE g.estado = 'aprobado') AS cantidad_gastos_aprobados,
    COALESCE(SUM(g.monto) FILTER (WHERE g.estado = 'aprobado'), 0) AS total_aprobado,
    COALESCE(SUM(g.monto) FILTER (WHERE g.estado = 'pendiente'), 0) AS total_pendiente,
    COALESCE(SUM(g.monto) FILTER (WHERE g.estado = 'rechazado'), 0) AS total_rechazado
FROM public.categorias_SGCGP c
LEFT JOIN public.gastos_SGCGP g ON g.categoria_id = c.id_categoria
GROUP BY c.id_categoria, c.nombre;

-- ============================================================
-- 19. VISTA DE CONTROL PRESUPUESTARIO
-- Se considera utilizado solo el gasto aprobado.
-- ============================================================

CREATE OR REPLACE VIEW public.vista_control_presupuesto_SGCGP
WITH (security_invoker = true)
AS
SELECT
    p.id_presupuesto,
    p.mes,
    p.anio,
    p.monto_limite,
    COALESCE(SUM(g.monto) FILTER (WHERE g.estado = 'aprobado'), 0) AS monto_utilizado,
    p.monto_limite - COALESCE(SUM(g.monto) FILTER (WHERE g.estado = 'aprobado'), 0) AS saldo_disponible,
    CASE
        WHEN p.monto_limite = 0 THEN 0
        ELSE ROUND(
            COALESCE(SUM(g.monto) FILTER (WHERE g.estado = 'aprobado'), 0)
            / p.monto_limite * 100,
            2
        )
    END AS porcentaje_utilizado
FROM public.presupuesto_SGCGP p
LEFT JOIN public.gastos_SGCGP g
    ON EXTRACT(MONTH FROM g.fecha) = p.mes
   AND EXTRACT(YEAR FROM g.fecha) = p.anio
GROUP BY p.id_presupuesto, p.mes, p.anio, p.monto_limite;

