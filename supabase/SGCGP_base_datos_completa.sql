CREATE TABLE IF NOT EXISTS public.usuarios_SGCGP (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id UUID UNIQUE REFERENCES auth.users(id) ON DELETE SET NULL,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    correo VARCHAR(255) UNIQUE,
    rol VARCHAR(30) NOT NULL DEFAULT 'solicitante'
        CHECK (rol IN ('administrador', 'encargado_gastos', 'solicitante')),
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_usuarios_rol_SGCGP
    ON public.usuarios_SGCGP(rol);
CREATE INDEX IF NOT EXISTS idx_usuarios_estado_SGCGP
    ON public.usuarios_SGCGP(estado);

CREATE OR REPLACE FUNCTION public.crear_perfil_SGCGP()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    INSERT INTO public.usuarios_SGCGP
        (auth_user_id, nombre, apellido, correo, rol)
    VALUES (
        NEW.id,
        COALESCE(NULLIF(NEW.raw_user_meta_data ->> 'nombre', ''), 'Usuario'),
        COALESCE(NULLIF(NEW.raw_user_meta_data ->> 'apellido', ''), 'Sin apellido'),
        NEW.email,
        'solicitante'
    )
    ON CONFLICT (auth_user_id) DO NOTHING;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_crear_perfil_SGCGP ON auth.users;
CREATE TRIGGER trg_crear_perfil_SGCGP
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.crear_perfil_SGCGP();

CREATE OR REPLACE FUNCTION public.proteger_perfil_SGCGP()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    -- Las escrituras realizadas desde el SQL Editor o un backend con rol
    -- privilegiado pueden no tener auth.uid(); se permiten para tareas admin.
    IF (SELECT auth.uid()) IS NOT NULL AND NOT public.es_admin_SGCGP() THEN
        IF NEW.auth_user_id IS DISTINCT FROM OLD.auth_user_id
           OR NEW.rol IS DISTINCT FROM OLD.rol
           OR NEW.estado IS DISTINCT FROM OLD.estado
           OR NEW.correo IS DISTINCT FROM OLD.correo
           OR NEW.id_usuario IS DISTINCT FROM OLD.id_usuario THEN
            RAISE EXCEPTION 'No tienes permisos para modificar campos protegidos del perfil.';
        END IF;
    END IF;
    NEW.updated_at := NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_proteger_perfil_SGCGP ON public.usuarios_SGCGP;
CREATE TRIGGER trg_proteger_perfil_SGCGP
BEFORE UPDATE ON public.usuarios_SGCGP
FOR EACH ROW EXECUTE FUNCTION public.proteger_perfil_SGCGP();

