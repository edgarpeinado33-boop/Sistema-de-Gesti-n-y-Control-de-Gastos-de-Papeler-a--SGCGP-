CREATE OR REPLACE FUNCTION public.registrar_historial_gasto_SGCGP()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_usuario INTEGER;
BEGIN
    SELECT u.id_usuario INTO v_usuario
    FROM public.usuarios_SGCGP u
    WHERE u.auth_user_id = (SELECT auth.uid())
    LIMIT 1;

    IF TG_OP = 'INSERT' THEN
        INSERT INTO public.historial_gastos_SGCGP
            (gasto_id, usuario_id, accion, descripcion, datos_anteriores, datos_nuevos)
        VALUES (NEW.id_gasto, v_usuario, 'INSERT', 'Registro de un gasto', NULL, TO_JSONB(NEW));
        RETURN NEW;
    ELSIF TG_OP = 'UPDATE' THEN
        INSERT INTO public.historial_gastos_SGCGP
            (gasto_id, usuario_id, accion, descripcion, datos_anteriores, datos_nuevos)
        VALUES (NEW.id_gasto, v_usuario, 'UPDATE', 'Modificación de un gasto', TO_JSONB(OLD), TO_JSONB(NEW));
        RETURN NEW;
    ELSIF TG_OP = 'DELETE' THEN
        -- Conserva la evidencia en JSONB sin mantener una FK al gasto eliminado.
        INSERT INTO public.historial_gastos_SGCGP
            (gasto_id, usuario_id, accion, descripcion, datos_anteriores, datos_nuevos)
        VALUES (NULL, v_usuario, 'DELETE', 'Eliminación de un gasto', TO_JSONB(OLD), NULL);
        RETURN OLD;
    END IF;
    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_historial_gastos_SGCGP ON public.gastos_SGCGP;
CREATE TRIGGER trg_historial_gastos_SGCGP
AFTER INSERT OR UPDATE OR DELETE ON public.gastos_SGCGP
FOR EACH ROW EXECUTE FUNCTION public.registrar_historial_gasto_SGCGP();

